"""Generate the isolated SQL Regression Guardian runner from shared Lite sources."""
from __future__ import annotations

import argparse
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / "backend" / "metrictrace_sdk" / "core.py"
REPLAY = ROOT / "backend" / "metrictrace_sdk" / "local_replay.py"
REGRESSION = ROOT / "backend" / "metrictrace_sdk" / "regression.py"

