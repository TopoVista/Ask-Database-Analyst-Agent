def _standalone(source: str) -> str:
    return (
        source.replace("from __future__ import annotations\n", "")
        .replace("from metrictrace_sdk.core import four_way_attribution, validate_metric_sql\n", "")
        .replace("from metrictrace_sdk.core import validate_metric_sql\n", "")
        .replace("from metrictrace_sdk.local_replay import LocalReplayError, LocalReplayLimits, execute_local_scalar, normalize_datasets\n", "")
    )


def build(destination: Path) -> Path:
    destination.parent.mkdir(parents=True, exist_ok=True)
    text = (
        "# Generated by release/build_sql_regression_guardian.py; do not edit directly.\n"
        "# Requires: duckdb==1.1.3, sqlglot==25.31.4\n"
        "# Embedded MetricTrace engine code is MIT licensed: Copyright © 2026 Souradeep Ghosh.\n"
        "from __future__ import annotations\n"
        + _standalone(CORE.read_text(encoding="utf-8"))
        + "\n\n" + _standalone(REPLAY.read_text(encoding="utf-8"))
        + "\n\n" + _standalone(REGRESSION.read_text(encoding="utf-8"))
        + WRAPPER
    )
    destination.write_text(text, encoding="utf-8", newline="\n")
    return destination


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=ROOT / "skills" / "metric-regression-investigator" / "scripts" / "run_regression.py")
    args = parser.parse_args()
    print(build(args.output))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
