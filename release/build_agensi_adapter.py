"""Generate the single-file Agensi runner from MetricTrace's shared Lite sources."""
from __future__ import annotations

import argparse
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / "backend" / "metrictrace_sdk" / "core.py"
REPLAY = ROOT / "backend" / "metrictrace_sdk" / "local_replay.py"

WRAPPER = r'''

def _read(path: str) -> str:
    try:
        return Path(path).read_text(encoding="utf-8")
    except OSError as exc:
        raise LocalReplayError("SQL definition file could not be read.") from exc


def main(argv=None) -> int:
    import argparse
    import json

    parser = argparse.ArgumentParser(description="MetricTrace local four-way replay")
    parser.add_argument("--old-dataset", required=True)
    parser.add_argument("--new-dataset", required=True)
    parser.add_argument("--old-sql-file", required=True)
    parser.add_argument("--new-sql-file", required=True)
    parser.add_argument("--allow-root", action="append", required=True,
                        help="Explicitly authorized directory; repeat for multiple roots")
    parser.add_argument("--timeout-seconds", type=float, default=20)
    args = parser.parse_args(argv)
    try:
        limits = LocalReplayLimits(timeout_seconds=args.timeout_seconds)
        replay = run_local_four_way(
            args.old_dataset, args.new_dataset, _read(args.old_sql_file), _read(args.new_sql_file),
            limits, allowed_roots=tuple(args.allow_root),
        )
        print(json.dumps({"ok": True, "replay": replay}, sort_keys=True))
        return 0
    except (LocalReplayError, ValueError) as exc:
        print(json.dumps({"ok": False, "error": {"code": "local_replay_error", "message": str(exc)}}))
        return 4


if __name__ == "__main__":
    raise SystemExit(main())
'''


def _standalone(source: str) -> str:
    return source.replace("from __future__ import annotations\n", "").replace(
        "from metrictrace_sdk.core import four_way_attribution, validate_metric_sql\n", ""
    )


def build(destination: Path) -> Path:
    destination.parent.mkdir(parents=True, exist_ok=True)
    text = (
        "# Generated by release/build_agensi_adapter.py; do not edit directly.\n"
        "# Requires: duckdb==1.1.3, sqlglot==25.31.4\n"
        "# Embedded MetricTrace engine code is MIT licensed: Copyright © 2026 Souradeep Ghosh.\n"
        "from __future__ import annotations\n"
        + _standalone(CORE.read_text(encoding="utf-8"))
        + "\n\n"
        + _standalone(REPLAY.read_text(encoding="utf-8"))
        + WRAPPER
    )
    destination.write_text(text, encoding="utf-8", newline="\n")
    return destination


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=ROOT / "release" / "agensi_candidate" / "scripts" / "run_replay.py")
    args = parser.parse_args()
    print(build(args.output))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
